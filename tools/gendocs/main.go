// Command gendocs renders the tfskel command tree to Markdown under
// docs/reference. It is the single source of the command reference: flags,
// defaults, and examples come from the same cobra definitions that back
// --help, so the docs cannot describe a flag the binary does not have.
//
// Run it through `make docs`. `make check` and CI regenerate and diff the
// output, so a change to cmd/ that is not regenerated fails the build.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/ishuar/tfskel/cmd"
	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

// header is prepended to every generated file so readers (and reviewers) see
// at a glance that edits belong in cmd/, not here.
const header = "<!-- Generated by `make docs` from the cobra command tree. Do not edit by hand: change the Long/Example strings in cmd/ and regenerate. -->\n\n"

func main() {
	out := flag.String("out", "docs/reference", "directory to write the Markdown reference into")
	flag.Parse()

	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	root := cmd.NewRootCmd()
	disableAutoGenTag(root)

	// Remove previously generated files only, so a renamed or removed command
	// does not leave a stale page behind. Anything else in the directory is
	// left alone.
	stale, err := filepath.Glob(filepath.Join(out, "tfskel*.md"))
	if err != nil {
		return fmt.Errorf("glob stale docs: %w", err)
	}
	for _, f := range stale {
		if err := os.Remove(f); err != nil {
			return fmt.Errorf("remove stale doc %s: %w", f, err)
		}
	}
	if err := os.MkdirAll(out, 0755); err != nil {
		return fmt.Errorf("create %s: %w", out, err)
	}

	prepend := func(string) string { return header }
	link := func(name string) string { return name }
	if err := doc.GenMarkdownTreeCustom(root, out, prepend, link); err != nil {
		return fmt.Errorf("generate markdown: %w", err)
	}
	return normalizeTrailingNewlines(out)
}

// normalizeTrailingNewlines rewrites each generated page to end with exactly
// one newline. cobra/doc emits a trailing blank line, and the repo's
// end-of-file-fixer pre-commit hook strips it; without this step every
// regeneration would differ from the committed files and docs-check would
// never pass. All I/O goes through an os.Root scoped to dir so a page name
// can never escape the output directory.
func normalizeTrailingNewlines(dir string) error {
	root, err := os.OpenRoot(dir)
	if err != nil {
		return fmt.Errorf("open %s: %w", dir, err)
	}
	defer root.Close()

	pages, err := fs.Glob(root.FS(), "tfskel*.md")
	if err != nil {
		return fmt.Errorf("glob generated docs: %w", err)
	}
	for _, page := range pages {
		b, err := fs.ReadFile(root.FS(), page)
		if err != nil {
			return fmt.Errorf("read %s: %w", page, err)
		}
		trimmed := append(bytes.TrimRight(b, "\n"), '\n')
		if bytes.Equal(b, trimmed) {
			continue
		}
		f, err := root.OpenFile(page, os.O_WRONLY|os.O_TRUNC, 0644)
		if err != nil {
			return fmt.Errorf("open %s for writing: %w", page, err)
		}
		_, werr := f.Write(trimmed)
		if cerr := f.Close(); werr == nil {
			werr = cerr
		}
		if werr != nil {
			return fmt.Errorf("write %s: %w", page, werr)
		}
	}
	return nil
}

// disableAutoGenTag turns off cobra's per-file "Auto generated on <date>"
// footer on every command. The date changes on each run, which would make
// the CI drift check fail on a no-op regeneration.
func disableAutoGenTag(c *cobra.Command) {
	c.DisableAutoGenTag = true
	for _, sub := range c.Commands() {
		disableAutoGenTag(sub)
	}
}
