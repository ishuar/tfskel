func TestRun(t *testing.T) {
	out := t.TempDir()

	// Files that must survive or disappear after a run.
	orphan := filepath.Join(out, "tfskel_removed_command.md")
	keep := filepath.Join(out, "notes.md")
	for _, f := range []string{orphan, keep} {
		if err := os.WriteFile(f, []byte("x\n"), 0644); err != nil {
			t.Fatal(err)
		}
	}

	if err := run(out); err != nil {
		t.Fatalf("run: %v", err)
	}

	if _, err := os.Stat(orphan); !os.IsNotExist(err) {
		t.Errorf("previously generated page %s should be removed, stat err = %v", orphan, err)
	}
	if _, err := os.Stat(keep); err != nil {
		t.Errorf("hand-written file %s should be left alone: %v", keep, err)
	}

	// One page per command, including the completion command cobra would add
	// at Execute() time.
	for _, want := range []string{
		"tfskel.md",
		"tfskel_init.md",
		"tfskel_scaffold.md",
		"tfskel_scaffold_workflows.md",
		"tfskel_validate.md",
		"tfskel_review.md",
		"tfskel_review_plan.md",
		"tfskel_version.md",
		"tfskel_completion.md",
	} {
		if _, err := os.Stat(filepath.Join(out, want)); err != nil {
			t.Errorf("expected page %s: %v", want, err)
		}
	}

	pages, err := filepath.Glob(filepath.Join(out, pagePattern))
	if err != nil {
		t.Fatal(err)
	}
	for _, page := range pages {
		b, err := os.ReadFile(page)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.HasPrefix(b, []byte(header)) {
			t.Errorf("%s: missing generated-file header", filepath.Base(page))
		}
		if !bytes.HasSuffix(b, []byte("\n")) || bytes.HasSuffix(b, []byte("\n\n")) {
			t.Errorf("%s: must end with exactly one newline", filepath.Base(page))
		}
		if bytes.Contains(b, []byte("Auto generated by spf13/cobra")) {
			t.Errorf("%s: auto-gen date footer must be disabled", filepath.Base(page))
		}
	}
}

// TestRunIsDeterministic guards the docs-check contract: regenerating over an
// existing output must produce byte-identical files, or CI fails on no-ops.
func TestRunIsDeterministic(t *testing.T) {
	out := t.TempDir()
	if err := run(out); err != nil {
		t.Fatal(err)
	}
	first := snapshot(t, out)

	if err := run(out); err != nil {
		t.Fatal(err)
	}
	second := snapshot(t, out)

	if len(first) != len(second) {
		t.Fatalf("page count changed between runs: %d vs %d", len(first), len(second))
	}
	for name, body := range first {
		if !bytes.Equal(body, second[name]) {
			t.Errorf("%s differs between runs", name)
		}
	}
}

func TestRunRejectsUnwritableDir(t *testing.T) {
	// A regular file where the directory should be: MkdirAll fails, and the
	// error must surface instead of being swallowed.
	file := filepath.Join(t.TempDir(), "not-a-dir")
	if err := os.WriteFile(file, nil, 0644); err != nil {
		t.Fatal(err)
	}
	err := run(file)
	if err == nil || !strings.Contains(err.Error(), "create") {
		t.Fatalf("expected create error, got %v", err)
	}
}

func snapshot(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	pages, err := filepath.Glob(filepath.Join(dir, pagePattern))
	if err != nil {
		t.Fatal(err)
	}
	got := make(map[string][]byte, len(pages))
	for _, p := range pages {
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		got[filepath.Base(p)] = b
	}
	return got
}
